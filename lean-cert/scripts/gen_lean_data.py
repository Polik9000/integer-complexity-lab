#!/usr/bin/env python3
"""Turn a lower-bound certificate (.jsonl or .jsonl.gz, research spec section 4) into Lean inputs.

Not part of the trust base: the Lean soundness theorem holds for *every* record list, so a bug
here can only make the Lean check fail (or prove a different, still true, statement -- the
target N and bound B are written in the Lean theorem by hand, not taken from this script).

Modes
  text  CERT OUTDIR CHUNKS   -> OUTDIR/chunk_XXX.txt (compact lines "P p a q..." / "C m j p e ..."),
                                 read in Lean with include_str and parsed by ICLCert.parse (native path)
  terms CERT OUTFILE MODNAME -> one Lean module defining `ICLCert.Data.<MODNAME>.chunks : List (List Rec)`
                                 as explicit Lean terms (kernel path, small certificates only)

Header and end records are validated (version, record count) and then dropped; the target and
claim are checked against the command line (--target N --claim J) if given.
"""
import gzip, json, sys, os, hashlib


def records(path):
    op = gzip.open if path.endswith(".gz") else open
    with op(path, "rt") as fh:
        lines = fh.read().splitlines()
    hdr = json.loads(lines[0])
    end = json.loads(lines[-1])
    assert hdr["type"] == "header" and hdr["version"] == 1, "bad header"
    assert end["type"] == "end", "missing end record"
    body = [json.loads(l) for l in lines[1:-1]]
    assert end["records"] == len(body), (end["records"], len(body))
    for r in body:
        for k, v in r.items():
            assert not isinstance(v, (float, bool)), "non-integer field"
    return hdr, body


def as_int(x):
    assert type(x) is int and x >= 0, x
    return x


def line_of(r):
    if r["type"] == "prime":
        return "P " + " ".join(str(as_int(x)) for x in [r["p"], r["a"], *r["q"]])
    if r["type"] == "claim":
        fs = []
        for p, e in r["f"]:
            fs += [as_int(p), as_int(e)]
        return "C " + " ".join(str(as_int(x)) for x in [int(r["m"]) if isinstance(r["m"], str) else r["m"], r["j"], *fs])
    raise ValueError(r["type"])


def term_of(r):
    if r["type"] == "prime":
        return "(.prime %d %d [%s])" % (r["p"], r["a"], ",".join(str(q) for q in r["q"]))
    m = int(r["m"]) if isinstance(r["m"], str) else r["m"]
    return "(.claim %d %d [%s])" % (m, r["j"], ",".join("(%d,%d)" % (p, e) for p, e in r["f"]))


def main():
    mode, cert, out = sys.argv[1], sys.argv[2], sys.argv[3]
    hdr, body = records(cert)
    print("header target=%s claim_gt=%s records=%d" % (hdr["target"], hdr["claim_gt"], len(body)), file=sys.stderr)
    if mode == "text":
        n = int(sys.argv[4])
        os.makedirs(out, exist_ok=True)
        size = (len(body) + n - 1) // n
        for i in range(n):
            part = body[i * size:(i + 1) * size]
            data = "".join(line_of(r) + "\n" for r in part)
            fn = os.path.join(out, "chunk_%03d.txt" % i)
            with open(fn, "w") as fh:
                fh.write(data)
            print("%s %d records %d bytes sha256 %s" % (fn, len(part), len(data),
                  hashlib.sha256(data.encode()).hexdigest()), file=sys.stderr)
    elif mode == "terms":
        modname = sys.argv[4]
        per = 500
        with open(out, "w") as fh:
            fh.write("import ICLCertCore\n\n/-! GENERATED by scripts/gen_lean_data.py from %s. -/\n\n"
                     % os.path.basename(cert))
            fh.write("namespace ICLCert.Data.%s\nopen ICLCert\n\n" % modname)
            names = []
            for i in range(0, len(body), per):
                nm = "c%d" % (i // per)
                names.append(nm)
                fh.write("def %s : List Rec := [\n  %s]\n\n" % (nm, ",\n  ".join(term_of(r) for r in body[i:i + per])))
            fh.write("def chunks : List (List Rec) := [%s]\n\nend ICLCert.Data.%s\n" % (", ".join(names), modname))
    else:
        raise SystemExit("unknown mode")


if __name__ == "__main__":
    main()
