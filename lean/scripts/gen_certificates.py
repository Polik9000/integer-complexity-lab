#!/usr/bin/env python3
"""Generate lean/IntegerComplexity/Certificates/M61.lean from certificates/m61/*.json.

Each JSON certificate becomes a Lean theorem `UpperBound n k` whose proof is the
expression itself, checked by the Lean kernel (`decide`-free: plain `rfl` on Nat
arithmetic, which the kernel evaluates with GMP-backed literals).

Run from the repository root:  python3 lean/scripts/gen_certificates.py
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from algorithms.expression import evaluate, to_lean  # noqa: E402

OUT = ROOT / "lean" / "IntegerComplexity" / "Certificates" / "M61.lean"


def ident(cid: str) -> str:
    return "c_" + re.sub(r"[^A-Za-z0-9]", "_", cid).lower()


def main() -> int:
    certs = sorted((ROOT / "certificates" / "m61").glob("*.json"))
    lines = [
        "import IntegerComplexity.Basic",
        "",
        "/-!",
        "# Kernel-checked upper bounds for `2^61 - 1`",
        "",
        "GENERATED by `lean/scripts/gen_certificates.py` from `certificates/m61/*.json`.",
        "Do not edit by hand. Each theorem proves `‖2^61 - 1‖ ≤ k` by exhibiting an expression.",
        "These are upper bounds only; they say nothing about optimality.",
        "-/",
        "",
        "namespace IntegerComplexity.Certificates.M61",
        "",
        "open IntegerComplexity",
        "",
    ]
    for p in certs:
        c = json.loads(p.read_text())
        ev = evaluate(c["expression"])
        assert ev.value == int(c["n"]) == 2**61 - 1 and ev.ones == c["ones"]
        name = ident(c["id"])
        lines += [
            f"/-- Certificate `{c['id']}` (`{p.relative_to(ROOT)}`). -/",
            f"def {name} : Expr :=",
            f"  {to_lean(c['expression'])}",
            "",
            f"theorem {name}_eval : {name}.eval = 2 ^ 61 - 1 := by rfl",
            "",
            f"theorem {name}_ones : {name}.ones = {ev.ones} := by rfl",
            "",
            f"theorem upperBound_{name} : UpperBound (2 ^ 61 - 1) {ev.ones} :=",
            f"  ⟨{name}, {name}_eval, Nat.le_of_eq {name}_ones⟩",
            "",
        ]
    lines += ["end IntegerComplexity.Certificates.M61", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)} with {len(certs)} certificates")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
