"""Generate a table-free lower-bound certificate + optimal expression for small n, as a Lean file.
Usage: python3 gen.py N MODNAME OUT.lean [tactic]   (needs exact table for values <= N)"""
import sys, math
sys.setrecursionlimit(100000)
import sys
import os
TAB = os.environ.get('ICL_TABLE', 'table_1e8.bin')  # the 10^8 table from run_cert.sh
N = int(sys.argv[1]); mod = sys.argv[2]; out = sys.argv[3]
tactic = sys.argv[4] if len(sys.argv) > 4 else 'decide +kernel'
c = open(TAB, 'rb').read()[:N + 1]
def lam(v):
    j, cc, p = 0, v**3, 1
    while p < cc: p *= 3; j += 1
    return j
def base(v): return max(1, lam(v))
done = {}  # v -> largest j emitted
order = []
stats = {'sums': 0, 'divs': 0}
def need(v, t):
    """ensure LB(v) >= t (t <= c[v])"""
    assert t <= c[v]
    if t <= base(v) or done.get(v, -1) >= t - 1: return
    prove(v, t - 1)
def prove(m, j):
    assert c[m] > j
    if 3**j < m**3:
        pass
    else:
        x = 1
        while 2 * x <= m and (x * (m - x))**3 <= 3**j:
            split(x, m - x, j); x += 1; stats['sums'] += 1
        d = 2
        while d * d <= m:
            if m % d == 0: split(d, m // d, j); stats['divs'] += 1
            d += 1
    done[m] = max(done.get(m, -1), j); order.append((m, j))
def split(p, q, j):
    tp = max(base(p), j + 1 - c[q]); tq = max(base(q), j + 1 - tp)
    need(p, tp); need(q, tq)
J = c[N] - 1
prove(N, J)
# optimal expression from the table
memo = {}
def expr(v):
    if v == 1: return '.one'
    if v in memo: return memo[v]
    for x in range(1, v // 2 + 1):
        if c[x] + c[v - x] == c[v]: r = f'(.add {expr(x)} {expr(v - x)})'; break
    else:
        for d in range(2, math.isqrt(v) + 1):
            if v % d == 0 and c[d] + c[v // d] == c[v]: r = f'(.mul {expr(d)} {expr(v // d)})'; break
    memo[v] = r; return r
body = order[:-1]; assert order[-1] == (N, J)
fuel = math.isqrt(max(m for m, _ in order)) + 5
with open(out, 'w') as f:
    f.write(f"""import IntegerComplexity.PoC.CheckerTrie
/-! GENERATED by gen.py: ‖{N}‖ = {c[N]}. {len(order)} claims, {stats['sums']} sum splits, {stats['divs']} divisor pairs. -/
namespace IntegerComplexity.PoC.{mod}
open IntegerComplexity
def body : List (Nat × Nat) := [{', '.join(f'({m}, {j})' for m, j in body)}]
def cert : List (Nat × Nat) := body ++ [({N}, {J})]
theorem cert_ok : checkAllT {fuel} .leaf cert = true := by {tactic}
theorem lb : LowerBound {N} {c[N]} := lowerBound_of_checkT cert_ok (List.mem_append_right _ (List.mem_singleton.mpr rfl))
def e : Expr := {expr(N)}
theorem ub : UpperBound {N} {c[N]} := ⟨e, by rfl, by decide⟩
theorem exact : HasComplexity {N} {c[N]} := ⟨ub, lb⟩
end IntegerComplexity.PoC.{mod}
""")
print(N, 'c=', c[N], 'claims', len(order), stats, 'fuel', fuel)
